"""The documentation file browser.

Two branches, and they behave differently on purpose.

«Корпоративные документы» is the library the project owns: real
`DocumentFolder` and `Document` rows, created and removed by administrators
through `documents/services.py`.

«Вложения» is a view of files that already belong to somebody else — act,
protocol and task attachments — generated by `documents/references.py`. It
stores nothing, copies nothing, and accepts no write from any role.

Two things every endpoint below does deliberately:

* the permission is checked *before* the HTTP method, so a user who types a
  management URL into the address bar gets a genuine 403 and not a «method not
  allowed» that hides the real answer;
* a file is never reachable by its media path. Both download views look the
  row up, re-ask the rule that owns it — `documents` for a corporate document,
  `acts`/`protocols`/`tasks` for a system attachment — and only then open
  storage.
"""

